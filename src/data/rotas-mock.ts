export function chaveRota(origem: string, destino: string) {
  return `${origem}|${destino}`;
}

export function getRotaEntreCidades(origem: string, destino: string): RotaMock {
  const key = chaveRota(origem, destino);
  if (ROTAS_MOCK[key]) return ROTAS_MOCK[key];
  return rotaLinearFallback(origem, destino);
}

function rotaLinearFallback(origem: string, destino: string): RotaMock {
  const a = coordCidade(origem);
  const b = coordCidade(destino);
  const points: LatLng[] = Array.from({ length: 21 }, (_, i) => {
    const t = i / 20;
    return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  });
  const km = distanciaPolylineKm(points);
  return { points, km: Math.round(km * 10) / 10, min: Math.max(1, Math.round((km / 60) * 60)) };
}
